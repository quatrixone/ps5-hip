#!/usr/bin/env python3
"""Generate a fixed binary32 engineering oracle using independent directed MPFR bounds."""
import argparse
import hashlib
import json
from pathlib import Path
import shlex
import shutil
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MPFR_INPUTS = {
    'mpfr-4.2.2.tar.xz': 'b67ba0383ef7e8a8563734e2e889ef5ec3c3b898a01d00fa0a6869ad81c6ce01',
    'mpfr.h': '588c2bd606cba060afb49cd024f9119e996089a341a99d1dc7e0367622335a13',
    'mpfr.texi': 'e43f21fef9676db4b6bc809a5f47310913881f9ee714bc15932a23cfc5fc7cf3',
}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def float_bits(value):
    return struct.unpack('<I', struct.pack('<f', value))[0]


def corpus():
    result = []

    def add(word):
        if word not in result:
            result.append(word)

    # Preserve signs and payloads as uint32 data throughout the native pipeline.
    for word in (0, 0x80000000, 1, 0x80000001, 0x007fffff, 0x807fffff,
                 0x00800000, 0x80800000, 0x00800001, 0x80800001,
                 0x7f800000, 0xff800000, 0x7fc00001, 0xffc12345,
                 0x7f7fffff, 0xff7fffff):
        add(word)
    # Neighbors of branch/cancellation/rounding/range anchors, including large trig reduction.
    anchors = [0x3e800000, 0x3ecccccd, 0x3f200000, 0x3f400000, 0x3f800000,
               0x3fc90fdb, 0x40490fdb, 0x41100000, 0x41800000, 0x47800000,
               float_bits(88), float_bits(89), float_bits(88.72283935546875),
               float_bits(103), float_bits(104), float_bits(103.97208404541016),
               float_bits(2**-13), float_bits(2**-26)]
    for anchor in anchors:
        for delta in (-1, 0, 1):
            add(anchor + delta)
            add((anchor + delta) | 0x80000000)
    state = 0x6f636d6c
    while len(result) < 257:
        state = (1664525 * state + 1013904223) & 0xffffffff
        add(float_bits(((state >> 8) % 32769 - 16384) / 1024))
    if len(result) != 257:
        raise ValueError('Fixed corpus exceeded its declared count')
    return result


def ordered(bits):
    return (~bits & 0xffffffff) if bits & 0x80000000 else bits ^ 0x80000000


def accepts(item, bits):
    if item['rule'] == 0:
        return bits == item['reference']
    if item['rule'] == 1:
        return bits & 0x7fc00000 == 0x7fc00000
    return (bits >> 31) == (item['reference'] >> 31) and (bits & 0x7fffffff) != 0 and bits & 0x7f800000 != 0x7f800000 and \
        ordered(item['lo']) <= ordered(bits) <= ordered(item['hi'])


def poison(item, index):
    return 0x3e800000 | ((index * 0x9e37 + 1) & 0x007fffff) if item['rule'] == 1 else 0x7fc00000 | (index + 1)


def validate_rows(inputs, rows):
    if len(inputs) != 257 or len(rows) != 1542:
        raise ValueError('Wrong corpus or output extent')
    for index, row in enumerate(rows):
        if (row['index'], row['operation']) != divmod(index, 6):
            raise ValueError('Oracle row ordering changed')
        if row['rule'] not in (0, 1, 2) or not accepts(row, row['reference']):
            raise ValueError('Reference is outside its own acceptance rule')
        if row['rule'] == 2 and ordered(row['lo']) > ordered(row['hi']):
            raise ValueError('Reversed acceptance interval')
        if accepts(row, poison(row, index)):
            raise ValueError('Poison is accepted')


def render_header(contract, digest):
    inputs = contract['input_bits']
    rows = [dict(zip(contract['expected_columns'], r)) for r in contract['expected']]
    prefix = '''// Generated by generate_math_oracle.py; no floating-point arithmetic in the checker.
#pragma once
#include <cstddef>
#include <cstdint>
namespace ps5hip_math {
inline constexpr std::size_t input_count = 257, output_words = 1542, groups = 5;
inline constexpr std::size_t threads = 64, allocation_output_words = 1920;
'''
    text = prefix + f'inline constexpr char contract_sha256[] = "{digest}";\n'
    text += 'inline constexpr std::uint32_t input_bits[input_count] = {\n'
    text += ''.join('  ' + ', '.join(f'0x{x:08x}u' for x in inputs[i:i+8]) + ',\n' for i in range(0, len(inputs), 8))
    text += '};\nstruct Expected { std::uint32_t lo, hi, reference; unsigned rule; };\n'
    text += 'inline constexpr Expected expected[output_words] = {\n'
    text += ''.join(f'  {{0x{r["lo"]:08x}u, 0x{r["hi"]:08x}u, 0x{r["reference"]:08x}u, {r["rule"]}u}},\n' for r in rows)
    text += '''};
constexpr std::uint32_t ordered(std::uint32_t bits) {
    return (bits & 0x80000000u) ? ~bits : (bits ^ 0x80000000u);
}
constexpr bool check_output(std::size_t index, std::uint32_t bits) {
    if (index >= output_words) return false;
    const auto& value = expected[index];
    if (value.rule == 0) return bits == value.reference;
    if (value.rule == 1) return (bits & 0x7fc00000u) == 0x7fc00000u;
    return (bits >> 31) == (value.reference >> 31) &&
        (bits & 0x7fffffffu) != 0 && (bits & 0x7f800000u) != 0x7f800000u &&
        ordered(value.lo) <= ordered(bits) && ordered(bits) <= ordered(value.hi);
}
constexpr std::uint32_t reference_bits(std::size_t index) {
    return index < output_words ? expected[index].reference : 0;
}
constexpr std::uint32_t poison_bits(std::size_t index) {
    return index < output_words && expected[index].rule == 1 ?
        0x3e800000u | ((static_cast<std::uint32_t>(index) * 0x9e37u + 1u) & 0x007fffffu) :
        0x7fc00000u | (static_cast<std::uint32_t>(index) + 1u);
}
} // namespace ps5hip_math
'''
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mpfr-inputs', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    source, output = args.mpfr_inputs.resolve(), args.output.resolve()
    if output.exists() or not any(output.is_relative_to(ROOT / x) for x in ('results', 'build')):
        parser.error('Output must be fresh and inside this checkout/results or build')
    for name, digest in MPFR_INPUTS.items():
        if sha(source / name) != digest:
            parser.error('Official MPFR input mismatch: ' + name)
    compiler = shutil.which('clang-18')
    if not compiler:
        parser.error('clang-18 unavailable')
    library = Path('/usr/lib/x86_64-linux-gnu/libmpfr.so.6').resolve()
    output.mkdir(parents=True)
    report = {'schema': 1, 'status': 'running', 'gpu_execution': False,
              'sources': {p: sha(ROOT / p) for p in ('tools/generate_math_oracle.py', 'tools/math_oracle_mpfr.c', 'kernels/ocml_math.hip')},
              'mpfr_inputs': MPFR_INPUTS, 'mpfr_library': {'path': str(library), 'sha256': sha(library)},
              'compiler': {'path': compiler, 'sha256': sha(Path(compiler))}, 'commands': []}

    def run(label, argv):
        result = subprocess.run(list(map(str, argv)), capture_output=True, text=True, timeout=120)
        (output / (label + '.stdout')).write_text(result.stdout)
        (output / (label + '.stderr')).write_text(result.stderr)
        report['commands'].append({'label': label, 'argv': list(map(str, argv)), 'exit_code': result.returncode})
        if result.returncode:
            raise RuntimeError(label + ' failed; preserve this output')
        return result.stdout

    try:
        inputs = corpus()
        (output / 'input-bits.txt').write_text(''.join(f'{x:08x}\n' for x in inputs))
        executable = output / 'mpfr-oracle'
        run('compile', [compiler, '-std=c11', '-O2', '-fno-fast-math', '-Wall', '-Wextra', '-Werror',
                        '-I' + str(source), '-MD', '-MF', output / 'headers.d', ROOT / 'tools/math_oracle_mpfr.c',
                        library, '-lgmp', '-o', executable])
        rows = [json.loads(line) for line in run('generate', [executable, output / 'input-bits.txt']).splitlines()]
        validate_rows(inputs, rows)
        contract = {'schema': 1, 'engineering_contract': True, 'hardware_validated': False,
                    'input_count': 257, 'output_words': 1542, 'groups': 5, 'threads': 64,
                    'allocation_output_words': 1920, 'input_bits': inputs,
                    'expected_columns': ['rule', 'lo', 'hi', 'reference'],
                    'expected': [[r[k] for k in ('rule', 'lo', 'hi', 'reference')] for r in rows],
                    'directed_certificate': {'file': 'generate.stdout', 'sha256': sha(output / 'generate.stdout')},
                    'mpfr_inputs': MPFR_INPUTS, 'mpfr_library': report['mpfr_library'],
                    'operations': ['fma(x,1.25,-0.5)', 'sqrt(RN32(abs(x)+0.25))', 'sin(x)', 'exp(x)',
                                   'log(RN32(abs(x)+0.25))', 'tanh(x)'],
                    'finite_ulp_budgets': [0, 0, 4, 3, 3, 5],
                    'ulp_definition': '2^max(floor(log2(abs(real_reference)))-23,-149); directed inner envelope; not adjacent-float distance or a universal HIP/OpenCL guarantee',
                    'exact_policy': 'Stronger engineering targets: fma/sqrt; all correctly-rounded zero/inf results; exp(+-0)=1; sin/tanh signedzero and |x|<=minnormal preserve bits; tanh |x|>=16 exact RN32; quietNaNs require quiet class, not payload/sign. Finite nonzero outputs must preserve mathematical sign and cannot flush tozero.',
                    'exp_extremes': 'Directed proofs exp(128)>2^128 and exp(-256)<2^-150; classify x>=128 and x<=-256 explicitly before MPFR evaluation',
                    'reference_source': {'device_libs_commit': '1e2c94795ee0d6ab8e2ff3035965a6b74e11b475',
                                         'accuracy_table': 'doc/OCML.md', 'llvm_commit': '3b5b5c1ec4a3095ab096dd780e84d7ab81f3d7ff'},
                    'generator_sources': report['sources'], 'mpfr_version': '4.2.2',
                    'limits': ['Fixed 257-input corpus only; no all-domain or GPU accuracy claim',
                               'MPFR oracle is independent of HIP/OCML code; host callback models are not ISA emulation',
                               'No signaling NaNs, exception flags or errno contract on device']}
        contract_path = output / 'math_oracle_contract.json'
        contract_path.write_text(json.dumps(contract, separators=(',', ':')) + '\n')
        (output / 'math_oracle.h').write_text(render_header(contract, sha(contract_path)))
        dependencies = shlex.split((output / 'headers.d').read_text().split(':', 1)[1].replace('\\\n', ' '))
        report['included_files'] = {p: sha(Path(p)) for p in sorted(set(dependencies))}
        linked = run('linked-libraries', ['ldd', executable])
        report['linked_libraries'] = {p: sha(Path(p)) for line in linked.splitlines()
                                      for p in line.split() if p.startswith('/') and Path(p).is_file()}
        for name, digest in report['sources'].items():
            if sha(ROOT / name) != digest:
                raise ValueError('Generator source changed during generation')
        report['status'] = 'passed_independent_offline_oracle_generation'
    except Exception as error:
        report['status'] = 'failed'; report['error'] = repr(error)
        raise
    finally:
        report['artifacts'] = {p.name: sha(p) for p in sorted(output.iterdir()) if p.is_file()}
        (output / 'receipt.json').write_text(json.dumps(report, indent=2) + '\n')
    print('Generated fixed MPFR reference; no GPU validation:', output)


if __name__ == '__main__':
    main()
